#!/usr/bin/env node
// Regenerates the per-asset table in docs/assets.md from public/models/manifest.json.
import { readFileSync, writeFileSync } from 'node:fs';

const m = JSON.parse(readFileSync('public/models/manifest.json', 'utf8'));
const MOD = {
  source: 'Axis/unit transform, decimation, meshopt compression',
  derived: 'Transform + partition or approximation from the named source mesh (see below)',
  modeled: 'Modeled by `tooth_layers.py` inside the source tooth shape',
  schematic: 'Generated by `build_assets.py` from computed landmarks',
};
const rows = Object.entries(m.meshes)
  .filter(([, v]) => v.stage !== 4)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, v]) => `| \`${k}\` | ${v.file} | ${v.sourceRef ?? '—'} | ${v.provenance} | ${MOD[v.provenance]} | ${v.triangles.toLocaleString('en')} |`);
const teeth = Object.keys(m.teeth).length;
const block = [
  '<!-- generated:start -->',
  '| Mesh key | File | BodyParts3D source | Provenance | Modifications | Triangles |',
  '|---|---|---|---|---|---|',
  ...rows,
  '',
  `Plus ${teeth} tooth assets in \`teeth/tooth-XX.glb\` (provenance \`modeled\`), each containing enamel, coronal and radicular dentin, cementum, periodontal ligament, pulp chamber and one mesh per root canal, derived from the corresponding tooth mesh above.`,
  '<!-- generated:end -->',
].join('\n');
const doc = readFileSync('docs/assets.md', 'utf8');
writeFileSync('docs/assets.md', doc.replace(/<!-- generated:start -->[\s\S]*<!-- generated:end -->/, block));
console.log(`docs/assets.md: ${rows.length} rows`);
